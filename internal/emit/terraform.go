// Provider versions are pinned exactly to the versions the generated modules were validated
// against (terraform validate and terraform test). Update them together with the tests.
const header = "# Generated by cgroupguard. Review before use; nothing here has been applied.\n"

func terraformModule(g plan.Group) ([]plan.File, bool) {
	dir := fmt.Sprintf("terraform/%s-%s/", g.Provider, g.Pool)
	switch g.Provider {
	case "gke":
		return gkeModule(dir, g)
	case "eks":
		return eksModule(dir, g)
	case "aks":
		return aksModule(dir, g)
	}
	return nil, false
}

func lifecycle(g plan.Group) string {
	pd := "false"
	if g.Stateful {
		pd = "true"
	}
	return "  lifecycle {\n    create_before_destroy = true\n    prevent_destroy       = " + pd + "\n  }\n"
}

func tfVar(name, typ, desc, def string) string {
	s := "variable " + hcl(name) + " {\n  type        = " + typ + "\n  description = " + hcl(desc) + "\n"
	if def != "" {
		s += "  default     = " + def + "\n"
	}
	return s + "}\n\n"
}

func gkeModule(dir string, g plan.Group) ([]plan.File, bool) {
	newName := g.Pool + "-v2"
	if len(newName) > 40 {
		return nil, false
	}
	machineDefault := ""
	if g.Instance != "" {
		machineDefault = hcl(g.Instance)
	}
	versions := header + `
terraform {
  required_version = ">= 1.5"

  required_providers {
    google = {
      source  = "hashicorp/google"
      version = "8.6.0"
    }
  }

  # Configure an encrypted remote backend with state locking before use, for example a
  # GCS bucket with versioning and CMEK. Do not keep state in the repository.
}

# Authenticate with workload identity federation or application default credentials.
# Never put keys in variables or files.
provider "google" {
  project = var.project
}
`
	vars := header + "\n" + tfVar("project", "string", "Google Cloud project that owns the cluster.", "") +
		tfVar("location", "string", "Cluster region or zone.", "") +
		tfVar("cluster_name", "string", "Name of the existing GKE cluster.", "") +
		tfVar("machine_type", "string", "Machine type; copy it from the old pool.", machineDefault) +
		tfVar("node_count", "number", "Nodes per zone for the replacement pool.", fmt.Sprint(len(g.Nodes)))
	vars = strings.TrimRight(vars, "\n") + "\n"
	main := header + `
# Blue/green: this ADDS a replacement pool whose nodes run cgroup v2. Cordon and drain
# the old pool (RUNBOOK.md), verify, then remove the old pool in your own configuration.
resource "google_container_node_pool" "cgroup_v2" {
  name       = ` + hcl(newName) + `
  project    = var.project
  location   = var.location
  cluster    = var.cluster_name
  node_count = var.node_count

  node_config {
    machine_type = var.machine_type

    linux_node_config {
      cgroup_mode = "CGROUP_MODE_V2"
    }

    # REVIEW: copy service_account, oauth_scopes, labels, taints and disk settings from the old pool.
  }

  upgrade_settings {
    strategy        = "SURGE"
    max_surge       = 1
    max_unavailable = 0
  }

` + lifecycle(g) + `}
`
	test := header + `
mock_provider "google" {}

variables {
  project      = "example-project"
  location     = "us-central1"
  cluster_name = "example-cluster"
  machine_type = "e2-standard-4"
}

run "replacement_pool_uses_cgroup_v2" {
  command = plan

  assert {
    condition     = google_container_node_pool.cgroup_v2.node_config[0].linux_node_config[0].cgroup_mode == "CGROUP_MODE_V2"
    error_message = "the replacement pool must request cgroup v2"
  }

  assert {
    condition     = google_container_node_pool.cgroup_v2.upgrade_settings[0].max_unavailable == 0
    error_message = "the replacement pool must not take nodes down during its own upgrades"
  }
}
`
	return []plan.File{{Path: dir + "versions.tf", Content: versions}, {Path: dir + "variables.tf", Content: vars}, {Path: dir + "main.tf", Content: main}, {Path: dir + "tests/cgroup_v2.tftest.hcl", Content: test}}, true
}

func eksModule(dir string, g plan.Group) ([]plan.File, bool) {
	newName := g.Pool + "-al2023"
	if len(newName) > 63 {
		return nil, false
	}
	ami := ""
	switch g.Arch {
	case "amd64":
		ami = hcl("AL2023_x86_64_STANDARD")
	case "arm64":
		ami = hcl("AL2023_ARM_64_STANDARD")
	}
	instance := "[]"
	if g.Instance != "" {
		instance = "[" + hcl(g.Instance) + "]"
	}
	versions := header + `
terraform {
  required_version = ">= 1.5"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "6.68.0"
    }
  }

  # Configure an encrypted S3 backend with locking before use. Do not keep state in the repository.
}

# Authenticate with an IAM role (SSO or OIDC). Never put access keys in variables or files.
provider "aws" {
  region = var.region
}
`
	vars := header + "\n" + tfVar("region", "string", "AWS region of the cluster.", "") +
		tfVar("cluster_name", "string", "Name of the existing EKS cluster.", "") +
		tfVar("node_role_arn", "string", "IAM role ARN for the nodes; copy it from the old node group.", "") +
		tfVar("subnet_ids", "list(string)", "Subnets for the nodes; copy them from the old node group.", "") +
		tfVar("ami_type", "string", "AL2023 or Bottlerocket AMI type (cgroup v2).", ami) +
		tfVar("instance_types", "list(string)", "Instance types; copy them from the old node group.", instance) +
		tfVar("desired_size", "number", "Desired node count.", fmt.Sprint(len(g.Nodes)))
	vars = strings.TrimRight(vars, "\n") + "\n"
	main := header + `
# Blue/green: this ADDS a replacement managed node group on a cgroup v2 AMI. Cordon and
# drain the old group (RUNBOOK.md), verify, then remove the old group in your own configuration.
resource "aws_eks_node_group" "cgroup_v2" {
  cluster_name    = var.cluster_name
  node_group_name = ` + hcl(newName) + `
  node_role_arn   = var.node_role_arn
  subnet_ids      = var.subnet_ids
  ami_type        = var.ami_type
  instance_types  = var.instance_types

  scaling_config {
    desired_size = var.desired_size
    min_size     = var.desired_size
    max_size     = var.desired_size * 2
  }

  update_config {
    max_unavailable = 1
  }

` + lifecycle(g) + `}
`
	test := header + `
mock_provider "aws" {}

variables {
  region         = "us-east-1"
  cluster_name   = "example-cluster"
  node_role_arn  = "arn:aws:iam::123456789012:role/example-node-role"
  subnet_ids     = ["subnet-0123456789abcdef0"]
  ami_type       = "AL2023_x86_64_STANDARD"
  instance_types = ["m5.large"]
}

run "replacement_group_uses_a_cgroup_v2_ami" {
  command = plan

  assert {
    condition     = can(regex("^(AL2023|BOTTLEROCKET)_", aws_eks_node_group.cgroup_v2.ami_type))
    error_message = "the replacement group must use AL2023 or Bottlerocket (cgroup v2)"
  }

  assert {
    condition     = aws_eks_node_group.cgroup_v2.update_config[0].max_unavailable == 1
    error_message = "node group updates must be rolling"
  }
}
`
	return []plan.File{{Path: dir + "versions.tf", Content: versions}, {Path: dir + "variables.tf", Content: vars}, {Path: dir + "main.tf", Content: main}, {Path: dir + "tests/cgroup_v2.tftest.hcl", Content: test}}, true
}

func aksModule(dir string, g plan.Group) ([]plan.File, bool) {
	base := g.Pool
	if len(base) > 9 {
		base = base[:9]
	}
	newName := strings.ToLower(strings.NewReplacer("-", "", "_", "", ".", "").Replace(base)) + "v2"
	if !plan.SafeName(newName) || len(newName) > 12 {
		return nil, false
	}
	sku := "Ubuntu2204"
	if g.OSFamily == "azurelinux" {
		sku = "AzureLinux3"
	}
	vmDefault := ""
	if g.Instance != "" {
		vmDefault = hcl(g.Instance)
	}
	versions := header + `
terraform {
  required_version = ">= 1.5"

  required_providers {
    azurerm = {
      source  = "hashicorp/azurerm"
      version = "5.8.0"
    }
  }

  # Configure an encrypted azurerm backend with state locking before use. Do not keep state in the repository.
}

# Authenticate with workload identity / OIDC or an Azure CLI login. Never put secrets in variables or files.
provider "azurerm" {
  features {}

  subscription_id = var.subscription_id
}
`
	vars := header + "\n" + tfVar("subscription_id", "string", "Azure subscription that owns the cluster.", "") +
		tfVar("kubernetes_cluster_id", "string", "Resource ID of the existing AKS cluster.", "") +
		tfVar("vm_size", "string", "VM size; copy it from the old pool.", vmDefault) +
		tfVar("node_count", "number", "Node count for the replacement pool.", fmt.Sprint(len(g.Nodes))) +
		tfVar("os_sku", "string", "Node OS SKU listed as cgroup v2 by AKS (Ubuntu2204 or AzureLinux3).", hcl(sku))
	vars = strings.TrimRight(vars, "\n") + "\n"
	main := header + `
# Blue/green: this ADDS a replacement pool on a cgroup v2 OS image. Cordon and drain the
# old pool (RUNBOOK.md), verify, then remove the old pool in your own configuration.
# If the old pool is the cluster's only system pool, set mode to "System" first.
resource "azurerm_kubernetes_cluster_node_pool" "cgroup_v2" {
  name                  = ` + hcl(newName) + `
  kubernetes_cluster_id = var.kubernetes_cluster_id
  vm_size               = var.vm_size
  node_count            = var.node_count
  os_type               = "Linux"
  os_sku                = var.os_sku
  mode                  = "User"

  upgrade_settings {
    max_surge = "33%"
  }

` + lifecycle(g) + `}
`
	test := header + `
mock_provider "azurerm" {}

variables {
  subscription_id       = "00000000-0000-0000-0000-000000000000"
  kubernetes_cluster_id = "/subscriptions/00000000-0000-0000-0000-000000000000/resourceGroups/example/providers/Microsoft.ContainerService/managedClusters/example"
  vm_size               = "Standard_D4s_v3"
}

run "replacement_pool_uses_a_cgroup_v2_os" {
  command = plan

  assert {
    condition     = contains(["Ubuntu2204", "AzureLinux3"], azurerm_kubernetes_cluster_node_pool.cgroup_v2.os_sku)
    error_message = "the replacement pool must use an OS SKU AKS lists as cgroup v2"
  }

  assert {
    condition     = azurerm_kubernetes_cluster_node_pool.cgroup_v2.mode == "User"
    error_message = "the replacement pool is a user pool"
  }
}
`
	return []plan.File{{Path: dir + "versions.tf", Content: versions}, {Path: dir + "variables.tf", Content: vars}, {Path: dir + "main.tf", Content: main}, {Path: dir + "tests/cgroup_v2.tftest.hcl", Content: test}}, true
}
