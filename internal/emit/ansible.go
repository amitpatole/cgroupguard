const rolePreflight = `---
- name: Read the running cgroup filesystem type
  ansible.builtin.command: stat -fc %T /sys/fs/cgroup/
  register: cgroupv2_fs
  changed_when: false
  check_mode: false
  tags: [always]

- name: Record whether this node still needs the migration
  ansible.builtin.set_fact:
    cgroupv2_needed: "{{ cgroupv2_fs.stdout != 'cgroup2fs' }}"
  tags: [always]

- name: Require a supported distribution family
  ansible.builtin.assert:
    that: ansible_facts['os_family'] in ['Debian', 'RedHat']
    fail_msg: Only Debian-like and RedHat-like hosts are supported; change this node by hand.
  when: cgroupv2_needed | bool

- name: Require Linux kernel 5.8 or newer
  ansible.builtin.assert:
    that: ansible_facts['kernel'] is version('5.8', '>=')
    fail_msg: cgroup v2 needs Linux kernel 5.8 or newer.
  when: cgroupv2_needed | bool

- name: Look for a GRUB drop-in directory
  ansible.builtin.stat:
    path: "{{ cgroupv2_grub_dropin_dir }}"
  register: cgroupv2_grub_dropin_dir_stat
  when: cgroupv2_needed | bool

- name: Find GRUB drop-in files that force cgroup v1
  ansible.builtin.find:
    paths: "{{ cgroupv2_grub_dropin_dir }}"
    patterns: '*.cfg'
    contains: '.*systemd\.(unified_cgroup_hierarchy=0|legacy_systemd_cgroup_controller)'
  register: cgroupv2_grub_dropins
  check_mode: false
  when:
    - cgroupv2_needed | bool
    - cgroupv2_grub_dropin_dir_stat.stat.isdir | default(false)

- name: Refuse to continue while a drop-in forces cgroup v1
  ansible.builtin.assert:
    that: cgroupv2_grub_dropins.matched == 0
    fail_msg: >-
      These files force cgroup v1 on the kernel command line and must be edited by hand before this role can work:
      {{ cgroupv2_grub_dropins.files | map(attribute='path') | join(', ') }}
  when:
    - cgroupv2_needed | bool
    - cgroupv2_grub_dropin_dir_stat.stat.isdir | default(false)

- name: Refuse to continue if the drop-in check could not read a path
  ansible.builtin.assert:
    that: cgroupv2_grub_dropins.skipped_paths | default({}) | length == 0
    fail_msg: "The GRUB drop-in directory could not be fully checked: {{ cgroupv2_grub_dropins.skipped_paths | default({}) }}"
  when:
    - cgroupv2_needed | bool
    - cgroupv2_grub_dropin_dir_stat.stat.isdir | default(false)

- name: Look for the container runtime and kubelet configuration
  ansible.builtin.stat:
    path: "{{ item }}"
  loop:
    - "{{ cgroupv2_containerd_config }}"
    - "{{ cgroupv2_kubelet_config }}"
  register: cgroupv2_config_files

- name: Require both configuration files
  ansible.builtin.assert:
    that: item.stat.exists
    fail_msg: "{{ item.item }} does not exist; this role supports containerd and a kubelet configuration file only."
  loop: "{{ cgroupv2_config_files.results }}"
  loop_control:
    label: "{{ item.item }}"
  when: cgroupv2_needed | bool
`

const roleMigrate = `---
- name: Migrate this node
  when: cgroupv2_needed | bool
  block:
    # Configuration is edited and backed up BEFORE the node is cordoned, so a failed
    # precondition or edit leaves the node serving traffic.
    - name: Back up boot, runtime and kubelet configuration
      ansible.builtin.copy:
        src: "{{ item }}"
        dest: "{{ item }}.cgroupguard.bak"
        remote_src: true
        force: false
        mode: preserve
      loop:
        - "{{ cgroupv2_grub_file }}"
        - "{{ cgroupv2_containerd_config }}"
        - "{{ cgroupv2_kubelet_config }}"

    - name: Record the current kernel arguments (RedHat-like)
      ansible.builtin.command: grubby --info=DEFAULT
      register: cgroupv2_grubby_info
      changed_when: false
      check_mode: false
      when: ansible_facts['os_family'] == 'RedHat'

    - name: Keep a copy of the kernel arguments for rollback (RedHat-like)
      ansible.builtin.copy:
        content: "{{ cgroupv2_grubby_info.stdout }}\n"
        dest: "{{ cgroupv2_kernel_args_backup }}"
        force: false
        mode: '0600'
      when: ansible_facts['os_family'] == 'RedHat'

    - name: Remove arguments that force cgroup v1 from the kernel command line
      ansible.builtin.replace:
        path: "{{ cgroupv2_grub_file }}"
        regexp: '^(GRUB_CMDLINE_LINUX(?:_DEFAULT)?=".*?)\s*systemd\.(?:unified_cgroup_hierarchy=0|legacy_systemd_cgroup_controller=[01])(.*")$'
        replace: '\1\2'
      register: cgroupv2_grub_cleanup
      when: ansible_facts['os_family'] == 'Debian'
      loop: [1, 2, 3]
      loop_control:
        label: pass {{ item }}

    - name: Add the unified cgroup hierarchy to the kernel command line
      ansible.builtin.lineinfile:
        path: "{{ cgroupv2_grub_file }}"
        regexp: '^(GRUB_CMDLINE_LINUX="(?!.*systemd\.unified_cgroup_hierarchy=1)[^"]*)"$'
        line: '\1 systemd.unified_cgroup_hierarchy=1"'
        backrefs: true
      register: cgroupv2_grub
      when: ansible_facts['os_family'] == 'Debian'

    - name: Regenerate the GRUB configuration (Debian-like)
      ansible.builtin.command: update-grub
      changed_when: true
      when: ansible_facts['os_family'] == 'Debian'

    - name: Switch the kernel command line to cgroup v2 with grubby (RedHat-like)
      ansible.builtin.command:
        argv:
          - grubby
          - --update-kernel=ALL
          - --remove-args=systemd.unified_cgroup_hierarchy=0 systemd.legacy_systemd_cgroup_controller=1
          - --args=systemd.unified_cgroup_hierarchy=1
      changed_when: true
      when: ansible_facts['os_family'] == 'RedHat'

    - name: Use the systemd cgroup driver in containerd
      ansible.builtin.replace:
        path: "{{ cgroupv2_containerd_config }}"
        regexp: '^(\s*SystemdCgroup\s*=\s*)false'
        replace: '\1true'

    - name: Require SystemdCgroup = true to be present in the containerd configuration
      ansible.builtin.command:
        argv:
          - grep
          - -Eq
          - '^\s*SystemdCgroup\s*=\s*true'
          - "{{ cgroupv2_containerd_config }}"
      changed_when: false
      check_mode: false
      when: not ansible_check_mode

    - name: Use the systemd cgroup driver in the kubelet
      ansible.builtin.lineinfile:
        path: "{{ cgroupv2_kubelet_config }}"
        regexp: '^cgroupDriver:'
        line: 'cgroupDriver: systemd'

    - name: Cordon the node
      kubernetes.core.k8s_drain:
        state: cordon
        name: "{{ cgroupv2_node_name }}"
        kubeconfig: "{{ cgroupv2_kubeconfig }}"
      delegate_to: "{{ cgroupv2_control_host }}"
      become: false
      no_log: "{{ cgroupv2_hide_kube_output }}"

    - name: Mark the node as being migrated by this role
      kubernetes.core.k8s:
        state: patched
        kind: Node
        name: "{{ cgroupv2_node_name }}"
        kubeconfig: "{{ cgroupv2_kubeconfig }}"
        definition:
          metadata:
            annotations:
              cgroupguard.io/migrating: 'true'
      delegate_to: "{{ cgroupv2_control_host }}"
      become: false
      no_log: "{{ cgroupv2_hide_kube_output }}"

    - name: Drain the node (respects PodDisruptionBudgets; never forced)
      kubernetes.core.k8s_drain:
        state: drain
        name: "{{ cgroupv2_node_name }}"
        kubeconfig: "{{ cgroupv2_kubeconfig }}"
        delete_options:
          ignore_daemonsets: true
          delete_emptydir_data: true
          disable_eviction: false
          force: false
          wait_timeout: "{{ cgroupv2_drain_timeout_seconds }}"
      delegate_to: "{{ cgroupv2_control_host }}"
      become: false
      no_log: "{{ cgroupv2_hide_kube_output }}"

    - name: Reboot the node
      ansible.builtin.reboot:
        reboot_timeout: "{{ cgroupv2_reboot_timeout_seconds }}"
`

const roleVerify = `---
- name: Read the cgroup filesystem type after the change
  ansible.builtin.command: stat -fc %T /sys/fs/cgroup/
  register: cgroupv2_fs_after
  changed_when: false
  check_mode: false

- name: Read the kernel command line
  ansible.builtin.command: cat /proc/cmdline
  register: cgroupv2_cmdline
  changed_when: false
  check_mode: false

- name: Require cgroup v2
  ansible.builtin.assert:
    that: cgroupv2_fs_after.stdout == 'cgroup2fs'
    fail_msg: >-
      The node is not on cgroup v2. It is left cordoned; roll back with cgroupv2-rollback.yml.
      Kernel command line: {{ cgroupv2_cmdline.stdout }}
  when: not ansible_check_mode

- name: Wait for the node to be Ready
  kubernetes.core.k8s_info:
    kind: Node
    name: "{{ cgroupv2_node_name }}"
    kubeconfig: "{{ cgroupv2_kubeconfig }}"
  register: cgroupv2_node
  until: >-
    cgroupv2_node.resources is defined and
    cgroupv2_node.resources | length > 0 and
    (cgroupv2_node.resources[0].status.conditions | default([]) | selectattr('type', 'equalto', 'Ready') | map(attribute='status') | first | default('False')) == 'True'
  retries: 60
  delay: 10
  delegate_to: "{{ cgroupv2_control_host }}"
  become: false
  no_log: "{{ cgroupv2_hide_kube_output }}"
  when: not ansible_check_mode

# Only a node this role cordoned (it carries the marker annotation) is uncordoned, so a
# node an administrator cordoned for another reason is never released by accident.
- name: Uncordon the node if this role cordoned it
  kubernetes.core.k8s_drain:
    state: uncordon
    name: "{{ cgroupv2_node_name }}"
    kubeconfig: "{{ cgroupv2_kubeconfig }}"
  delegate_to: "{{ cgroupv2_control_host }}"
  become: false
  no_log: "{{ cgroupv2_hide_kube_output }}"
  when:
    - not ansible_check_mode
    - cgroupv2_node.resources[0].metadata.annotations['cgroupguard.io/migrating'] | default('false') == 'true'

- name: Remove the migration marker
  kubernetes.core.k8s:
    state: patched
    kind: Node
    name: "{{ cgroupv2_node_name }}"
    kubeconfig: "{{ cgroupv2_kubeconfig }}"
    definition:
      metadata:
        annotations:
          cgroupguard.io/migrating: null
  delegate_to: "{{ cgroupv2_control_host }}"
  become: false
  no_log: "{{ cgroupv2_hide_kube_output }}"
  when:
    - not ansible_check_mode
    - cgroupv2_node.resources[0].metadata.annotations['cgroupguard.io/migrating'] | default('false') == 'true'
`

const roleRollback = `---
- name: Restore the configuration backups
  ansible.builtin.copy:
    src: "{{ item }}.cgroupguard.bak"
    dest: "{{ item }}"
    remote_src: true
    mode: preserve
  loop:
    - "{{ cgroupv2_grub_file }}"
    - "{{ cgroupv2_containerd_config }}"
    - "{{ cgroupv2_kubelet_config }}"

- name: Delete the restored backups so a later attempt takes fresh ones
  ansible.builtin.file:
    path: "{{ item }}.cgroupguard.bak"
    state: absent
  loop:
    - "{{ cgroupv2_grub_file }}"
    - "{{ cgroupv2_containerd_config }}"
    - "{{ cgroupv2_kubelet_config }}"

- name: Regenerate the GRUB configuration (Debian-like)
  ansible.builtin.command: update-grub
  changed_when: true
  when: ansible_facts['os_family'] == 'Debian'

- name: Read the kernel arguments recorded before the migration (RedHat-like)
  ansible.builtin.slurp:
    src: "{{ cgroupv2_kernel_args_backup }}"
  register: cgroupv2_recorded_args
  when: ansible_facts['os_family'] == 'RedHat'

- name: Work out which cgroup v1 arguments to put back (RedHat-like)
  ansible.builtin.set_fact:
    cgroupv2_v1_args_to_restore: >-
      {{ ['systemd.unified_cgroup_hierarchy=0', 'systemd.legacy_systemd_cgroup_controller=1']
         | select('in', (cgroupv2_recorded_args.content | b64decode)) | join(' ') }}
  when: ansible_facts['os_family'] == 'RedHat'

- name: Remove the unified cgroup hierarchy argument with grubby (RedHat-like)
  ansible.builtin.command: grubby --update-kernel=ALL --remove-args=systemd.unified_cgroup_hierarchy=1
  changed_when: true
  when: ansible_facts['os_family'] == 'RedHat'

- name: Restore the original cgroup v1 arguments with grubby (RedHat-like)
  ansible.builtin.command:
    argv:
      - grubby
      - --update-kernel=ALL
      - "--args={{ cgroupv2_v1_args_to_restore }}"
  changed_when: true
  when:
    - ansible_facts['os_family'] == 'RedHat'
    - cgroupv2_v1_args_to_restore | length > 0

- name: Delete the recorded kernel arguments (RedHat-like)
  ansible.builtin.file:
    path: "{{ cgroupv2_kernel_args_backup }}"
    state: absent
  when: ansible_facts['os_family'] == 'RedHat'

- name: Reboot the node
  ansible.builtin.reboot:
    reboot_timeout: "{{ cgroupv2_reboot_timeout_seconds }}"
`

const ansibleReadme = `# Generated Ansible project

Nothing here has been run. Review it, then:

1. ` + "`ansible-galaxy collection install -r requirements.yml`" + ` (the collection version is pinned).
2. Fill in ansible_user and each ansible_host in inventory.yml; set KUBECONFIG for the control host.
3. Dry run: ` + "`ansible-playbook cgroupv2-migrate.yml --check --diff`" + `.
4. Read-only checks: ` + "`ansible-playbook cgroupv2-migrate.yml --tags preflight`" + `.
5. Migrate: the canary group runs first, one node at a time, and the play stops on the first failure.
6. Roll back a node: ` + "`ansible-playbook cgroupv2-rollback.yml --limit NODE`" + `.

Kubernetes permissions: the identity in the kubeconfig needs, at least, get/list/patch on nodes, get/list on pods and create on pods/eviction
(that is what draining uses); check with kubectl auth can-i before running. The role marks nodes it cordons with the annotation
cgroupguard.io/migrating and uncordons only those.

Security: use SSH keys in an agent or SSM, keep secrets in Ansible Vault, give the connecting user a
least-privilege sudo rule, and keep kubeconfig output hidden (the role sets no_log on Kubernetes tasks).
`

func ansibleProject(target string, groups []plan.Group) []plan.File {
	var inv strings.Builder
	inv.WriteString("---\n# Generated by cgroupguard. Fill in the REPLACE_WITH_* values; nothing secret belongs in this file.\nall:\n  vars:\n    ansible_user: REPLACE_WITH_SSH_USER\n    cgroupv2_control_host: localhost\n  children:\n")
	// The canary is the first node of the first (smallest blast radius) group.
	var canary string
	var rest []string
	for gi, g := range groups {
		for ni, n := range g.Nodes {
			if gi == 0 && ni == 0 {
				canary = n
				continue
			}
			rest = append(rest, n)
		}
	}
	host := func(n string) string {
		return "        " + yamlStr(n) + ":\n          ansible_host: REPLACE_WITH_SSH_ADDRESS\n          cgroupv2_node_name: " + yamlStr(n) + "\n"
	}
	inv.WriteString("    cgroupv2_canary:\n      hosts:\n" + host(canary))
	inv.WriteString("    cgroupv2_rest:\n      hosts:\n")
	if len(rest) == 0 {
		inv.WriteString("        {}\n")
	}
	for _, n := range rest {
		inv.WriteString(host(n))
	}
	base := "ansible/"
	role := base + "roles/cgroupv2/"
	return []plan.File{
		{Path: base + ".ansible-lint", Content: ansibleLintCfg},
		{Path: base + ".yamllint", Content: yamllintCfg},
		{Path: base + "README.md", Content: ansibleReadme},
		{Path: base + "ansible.cfg", Content: ansibleCfg},
		{Path: base + "cgroupv2-migrate.yml", Content: playbook},
		{Path: base + "cgroupv2-rollback.yml", Content: rollbackPlaybook},
		{Path: base + "inventory.yml", Content: strings.Replace(inv.String(), "        {}\n", "        {}\n", 1)},
		{Path: base + "requirements.yml", Content: ansibleRequirements},
		{Path: role + "defaults/main.yml", Content: roleDefaults},
		{Path: role + "meta/main.yml", Content: roleMeta},
		{Path: role + "tasks/main.yml", Content: roleMain},
		{Path: role + "tasks/preflight.yml", Content: rolePreflight},
		{Path: role + "tasks/migrate.yml", Content: roleMigrate},
		{Path: role + "tasks/verify.yml", Content: roleVerify},
		{Path: role + "tasks/rollback.yml", Content: roleRollback},
	}
}
