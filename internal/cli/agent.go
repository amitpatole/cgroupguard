package cli

import (
	"fmt"
	"io"
	"strings"

	"github.com/amitpatole/cgroupguard/internal/agent"
	"github.com/amitpatole/cgroupguard/internal/audit"
	"github.com/amitpatole/cgroupguard/internal/plan"
	"github.com/amitpatole/cgroupguard/internal/redact"
	"github.com/spf13/cobra"
)

type agentOpts struct {
	scan                                      scanOpts
	provider, model, baseURL, keyEnv, auditTo string
	insecure, reveal, sendImages              bool
	maxSteps, maxTokens                       int
}

func (o *agentOpts) bind(c *cobra.Command) {
	f := c.Flags()
	o.scan.bind(f)
	f.StringVar(&o.provider, "provider", "", "Model provider: anthropic or openai-compatible (Ollama, vLLM and others)")
	f.StringVar(&o.model, "model", "", "Model name")
	f.StringVar(&o.baseURL, "base-url", "", "Provider base URL (required for openai-compatible, for example http://localhost:11434/v1)")
	f.StringVar(&o.keyEnv, "api-key-env", "", "Name of the environment variable holding the API key (never pass keys on the command line)")
	f.BoolVar(&o.insecure, "allow-insecure-http", false, "Allow plain http to a non-loopback host")
	f.BoolVar(&o.reveal, "reveal-names", false, "Send real node, namespace and workload names instead of pseudonyms (secrets are still removed)")
	f.BoolVar(&o.sendImages, "send-images", false, "Also send full image references (secrets are still removed)")
	f.IntVar(&o.maxSteps, "max-steps", 8, "Maximum model calls")
	f.IntVar(&o.maxTokens, "max-tokens", 60000, "Maximum total tokens for the run")
	f.StringVar(&o.auditTo, "audit-log", "", "Write a hash-chained audit log to this new file")
}

func (o *agentOpts) audit() (*agent.Audit, func(), error) {
	if o.auditTo == "" {
		return nil, func() {}, nil
	}
	return audit.Create(o.auditTo)
}

func (o *agentOpts) env(cmd *cobra.Command) (*agent.Env, error) {
	r, err := o.scan.scan(cmd)
	if err != nil {
		return nil, err
	}
	p, err := plan.Build(r, plan.Options{})
	if err != nil {
		return nil, err
	}
	return &agent.Env{Report: r, Plan: p, R: redact.New(o.reveal), SendImages: o.sendImages, Docs: agent.LoadDocs()}, nil
}

func agentCommand(out, errOut io.Writer, code *int) *cobra.Command {
	root := &cobra.Command{Use: "agent", Short: "Optional read-only assistant: explanations and an MCP server (never changes anything)"}

	var ex agentOpts
	explain := &cobra.Command{Use: "explain", Short: "Ask a model to explain the scan and plan (advisory commentary only)", Args: cobra.NoArgs,
		Long: "Sends redacted, pseudonymized data to the model you configure. The model can only call read-only tools. Its text is labeled advisory and can never change the report, the plan or any file. Works without any model: the deterministic commands do not use this.",
		RunE: func(cmd *cobra.Command, args []string) error {
			if ex.provider == "" {
				return fmt.Errorf("--provider is required")
			}
			if ex.keyEnv == "" && ex.provider == "anthropic" {
				ex.keyEnv = "ANTHROPIC_API_KEY"
			}
			llm, err := agent.NewLLM(agent.ProviderConfig{Kind: ex.provider, Model: ex.model, BaseURL: ex.baseURL, APIKeyEnv: ex.keyEnv, AllowInsecure: ex.insecure})
			if err != nil {
				return err
			}
			env, err := ex.env(cmd)
			if err != nil {
				return err
			}
			au, closeLog, err := ex.audit()
			if err != nil {
				return err
			}
			defer closeLog()
			res, runErr := agent.Run(cmd.Context(), llm, env, agent.Config{MaxSteps: ex.maxSteps, MaxTotalTokens: ex.maxTokens}, au, "Explain this cgroup v1 to v2 readiness scan and its remediation plan for the operator. Highlight the highest blast-radius risks and what to do first.")
			if runErr != nil && res.Text == "" {
				if runErr == agent.ErrBudget {
					_, _ = fmt.Fprintf(errOut, "agent stopped: %s; no commentary was produced\n", res.Reason)
					*code = 1
					return nil
				}
				return runErr
			}
			var b strings.Builder
			b.WriteString("# AI commentary (advisory, unverified)\n\n> Generated by " + llm.Name() + " from redacted data. The deterministic report and plan are authoritative; this text cannot change them. Verify every statement before acting.\n\n")
			b.WriteString(strings.ReplaceAll(res.Text, "\r", "") + "\n")
			if len(res.Suggestions) > 0 {
				b.WriteString("\n## Parameter suggestions (advisory)\n\n")
				for _, s := range res.Suggestions {
					b.WriteString(fmt.Sprintf("- group %s: max surge %d, drain timeout %d minutes\n", env.R.Unmap(s.Group), s.MaxSurge, s.DrainTimeoutMinutes))
				}
			}
			if runErr != nil {
				b.WriteString("\n> Incomplete: " + res.Reason + ".\n")
				*code = 1
			}
			_, err = io.WriteString(out, b.String())
			return err
		}}
	ex.bind(explain)
	explain.MarkFlagsMutuallyExclusive("input", "local")

	var mc agentOpts
	mcp := &cobra.Command{Use: "mcp", Short: "Serve the read-only tools over MCP (stdio)", Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			env, err := mc.env(cmd)
			if err != nil {
				return err
			}
			au, closeLog, err := mc.audit()
			if err != nil {
				return err
			}
			defer closeLog()
			return agent.ServeMCP(cmd.Context(), cmd.InOrStdin(), out, env, agent.Policy{}, au, 0)
		}}
	mc.bind(mcp)
	mcp.MarkFlagsMutuallyExclusive("input", "local")

	verify := &cobra.Command{Use: "verify-log FILE", Short: "Check the hash chain of an audit log", Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			f, err := openSnapshotLike(args[0])
			if err != nil {
				return err
			}
			defer f.Close()
			n, err := agent.VerifyLog(f)
			if err != nil {
				return err
			}
			_, err = fmt.Fprintf(out, "%d entries, hash chain intact\n", n)
			return err
		}}
	root.AddCommand(explain, mcp, verify)
	return root
}
